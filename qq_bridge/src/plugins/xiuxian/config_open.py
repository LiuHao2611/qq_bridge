def find_bounty(name: str):
    """按任务名精确匹配（也允许去掉「寻找/捕捉/击杀/活捉/阻止/重伤」前缀的简称）。"""
    name = (name or "").strip()
    if not name:
        return None
    for row in OPEN_BOUNTIES:
        if row[1] == name:
            return row
    for row in OPEN_BOUNTIES:
        short = row[1]
        for pre in ("寻找", "捕捉", "击杀", "活捉", "阻止", "重伤"):
            if short.startswith(pre):
                short = short[len(pre):]
                break
        if short == name:
            return row
    return None


