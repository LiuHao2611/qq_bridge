#: 每条主动技的斗气/冷却（异火属「特殊」阶，沿用 skill_book 的 _MP_BY_TIER/_CD_BY_TIER）
ACTIVE_MP = 0.50
ACTIVE_CD = 3


def active_of(name: str) -> dict | None:
    return FLAME_SKILLS.get(str(name), {}).get("active")


def passive_of(name: str) -> dict | None:
    return FLAME_SKILLS.get(str(name), {}).get("passive")


def owned(p, name: str) -> bool:
    """该异火是否已被玩家收服（帝炎走 diyan 成就位，其余看喂养等级）。"""
    if name == cfg.FLAME_DIYAN:
        return bool(p.get("diyan"))
    return int((p.get("flames") or {}).get(name, 0)) > 0


def entries_for(p) -> list[dict]:
    """已收服异火的主动技，转成与 skills._from_book 完全同形的斗技条目。

    由 ``skills.entries_for`` 合并进玩家技能目录，因此四槽上阵、斗技列表、
    斗技详情、战斗选招、卡片渲染全部自动支持，无需改 185 条 SKILL_BOOK。
    """
    out: list[dict] = []
    for name, rec in FLAME_SKILLS.items():
        if not owned(p, name):
            continue
        a = rec["active"]
        out.append({
            "name": a["name"],
            "tier": "特殊",
            "faction": "异火",
            "mp": ACTIVE_MP,
            "dmg": float(a["dmg"]),
            "unlock": 1,               # 收服即可用，不再卡等级
            "desc": a["desc"],
            "brief": a["brief"],
            "rank": "异火",
            "kind": a["kind"],
            "scope": a["scope"],
            "source": a["source"],
            "novel": a["novel"],
            "cd": ACTIVE_CD,
            "core": False,
            "flame": name,             # 便于「斗技」里标注来自哪朵异火
        })
    return out
